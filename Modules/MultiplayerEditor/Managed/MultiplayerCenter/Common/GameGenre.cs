namespace Unity.Multiplayer.Center.Common
{
    /// <summary>
    /// A list of game genres with examples and getting started samples supported by the Unity Multiplayer packages.
    /// </summary>
    internal enum GameGenre
    {
        /// <summary>
        /// Used to target Casual or Cooperative games.
        /// </summary>
        Casual = 0,
        /// <summary>
        /// Used to target Competitive games.
        /// </summary>
        Competitive = 1,
        /// <summary>
        /// Used to target Turn-Based or Event-Driven games.
        /// </summary>
        EventDriven = 2,
    }
}

using System;
using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEditor.AssetImporters;
using UnityEditor.UIElements;
using UnityEngine;
using UnityEngine.Pool;
using UnityEngine.UIElements;

namespace UnityEditor
{
    [CustomEditor(typeof(TrueTypeFontImporter))]
    [CanEditMultipleObjects]
    internal class TrueTypeFontImporterInspector : AssetImporterEditor
    {
        private static class Style
        {
            public static readonly string RenderingMode = L10n.Tr("Rendering Mode", null);
            public static readonly string TextureCase = L10n.Tr("Character", null);
            public static readonly string AscentCalculationMode = L10n.Tr("Ascent Calculation Mode", null);
            public static readonly string CustomChars = L10n.Tr("Custom Chars", null);
            public static readonly string BoundCalculation = L10n.Tr("Use Legacy Bounds", null);
            public static readonly string ShouldRoundAdvanceValue = L10n.Tr("Should Round Advance Value", null);
            public static readonly string IncludeFontData = L10n.Tr("Include Font Data", null);
            public static readonly string FamilyName = L10n.Tr("Family Name", null);
            public static readonly string FamilyNameTooltip = L10n.Tr("This is the family name of this font. It will always be included to perform the references check, along with other names in the Font Name list.", null);
            public static readonly string FontName = L10n.Tr("Font Names", null);
            public static readonly string FontReferences = L10n.Tr("References to other fonts in project", null);
            public static readonly string NoFontReference = L10n.Tr("No references to other fonts in project.", null);

            public static readonly string FormatUnsupported = L10n.Tr("Format of selected font is not supported by Unity.", null);
            public static readonly string ReferencesInformation = L10n.Tr("These are automatically generated by the inspector if any of the font names you supplied match fonts present in your project, which will then be used as fallbacks for this font.", null);
        }

        SerializedProperty m_FontSize;
        SerializedProperty m_TextureCase;
        SerializedProperty m_IncludeFontData;
        SerializedProperty m_FontName;
        SerializedProperty m_FontNames;
        SerializedProperty m_CustomCharacters;
        SerializedProperty m_FontRenderingMode;
        SerializedProperty m_AscentCalculationMode;
        SerializedProperty m_UseLegacyBoundsCalculation;
        SerializedProperty m_ShouldRoundAdvanceValue;
        List<Font> m_FallbackFontReferences;

        bool m_FormatSupported;
        bool m_ReferencesExpanded = false;

        public override void OnEnable()
        {
            base.OnEnable();
            if (!AreImporterTargetsValid()) // asset gone: base already logged and bailed
                return;

            m_FontSize = serializedObject.FindProperty("m_FontSize");
            m_TextureCase = serializedObject.FindProperty("m_ForceTextureCase");
            m_IncludeFontData = serializedObject.FindProperty("m_IncludeFontData");
            m_FontName = serializedObject.FindProperty("m_FontName");
            m_FontNames = serializedObject.FindProperty("m_FontNames");
            m_CustomCharacters = serializedObject.FindProperty("m_CustomCharacters");
            m_FontRenderingMode = serializedObject.FindProperty("m_FontRenderingMode");
            m_AscentCalculationMode = serializedObject.FindProperty("m_AscentCalculationMode");
            m_UseLegacyBoundsCalculation = serializedObject.FindProperty("m_UseLegacyBoundsCalculation");
            m_ShouldRoundAdvanceValue = serializedObject.FindProperty("m_ShouldRoundAdvanceValue");
            UpdateFontReferencesList();

            m_FormatSupported = true;
            foreach (UnityEngine.Object target in targets)
            {
                var importer = target as TrueTypeFontImporter;
                if (importer == null || !importer.IsFormatSupported())
                    m_FormatSupported = false;
            }

            m_ReferencesExpanded = EditorPrefs.GetBool("TrueTypeFontImporterInspector_m_ReferencesExpanded");
        }

        void UpdateFontReferencesList()
        {
            var fonts = serializedObject.FindProperty("m_FallbackFontReferences");
            m_FallbackFontReferences = new List<Font>();
            var it = fonts.FindPropertyRelative("Array.size");
            while (it.Next(false) && it.propertyPath.StartsWith(fonts.propertyPath))
            {
                m_FallbackFontReferences.Add(it.hasMultipleDifferentValues ? null : (Font)it.objectReferenceValue);
            }
        }

        public override void OnDisable()
        {
            EditorPrefs.SetBool("TrueTypeFontImporterInspector_m_ReferencesExpanded", m_ReferencesExpanded);
            base.OnDisable();
        }

        protected override bool needsApplyRevert
        {
            get
            {
                if (!m_FormatSupported)
                    return false;
                return base.needsApplyRevert;
            }
        }

        void UpdateFontReferences()
        {
            serializedObject.ApplyModifiedProperties();
            for (var i = 0; i < targets.Length; i++)
            {
                var importer = (TrueTypeFontImporter)targets[i];
                var currentNames = importer.fontNames;
                int size = m_FontNames.hasMultipleDifferentValues ? currentNames.Length : m_FontNames.arraySize;
                var perImporterName = new List<string>(size);
                for (int j = 0; j < size; j++)
                {
                    var prop = m_FontNames.GetArrayElementAtIndex(j);
                    if (prop != null && prop.isValid)
                        perImporterName.Add(prop.hasMultipleDifferentValues ? currentNames[j] : prop.stringValue);
                    else
                        perImporterName.Add(currentNames[j]);
                }
                var fallbacks = importer.LookupFallbackFontReferences(perImporterName.ToArray());
                importer.fontReferences = fallbacks;
            }
            serializedObject.Update();
            UpdateFontReferencesList();
        }

        static string GetUniquePath(string basePath, string extension)
        {
            for (int i = 0; i < 10000; i++)
            {
                string path = string.Format("{0}{1}.{2}", basePath, (i == 0 ? string.Empty : i.ToString()), extension);
                if (!File.Exists(path))
                    return path;
            }
            return "";
        }

        [MenuItem("CONTEXT/TrueTypeFontImporter/Create Editable Copy", validate = true)]
        static bool CreateEditableCopy_Validate(MenuCommand command)
        {
            var importer = (TrueTypeFontImporter)command.context;
            return AssetDatabase.Contains(importer);
        }

        [MenuItem("CONTEXT/TrueTypeFontImporter/Create Editable Copy")]
        static void CreateEditableCopy(MenuCommand command)
        {
            var importer = (TrueTypeFontImporter)command.context;
            if (importer.fontTextureCase == FontTextureCase.Dynamic)
            {
                EditorDialog.DisplayAlertDialog(
                    titleText: "Cannot generate editable font asset for dynamic fonts",
                    messageText: "Please reimport the font in a different mode.",
                    buttonText: default);
                return;
            }
            string basePath = Path.Combine(Path.GetDirectoryName(importer.assetPath), Path.GetFileNameWithoutExtension(importer.assetPath));
            EditorGUIUtility.PingObject(importer.GenerateEditableFont(GetUniquePath(basePath + "_copy", "fontsettings")));
        }

        public override VisualElement CreateInspectorGUI()
        {
            var root = new VisualElement();

            if (!m_FormatSupported)
            {
                root.Add(new HelpBox(Style.FormatUnsupported, HelpBoxMessageType.Warning));
                return root;
            }

            ClampFontSize(m_FontSize);
            var fontSizeField = new IntegerField(m_FontSize.displayName) { isDelayed = true };
            fontSizeField.AddToClassList(IntegerField.alignedFieldUssClassName);
            fontSizeField.BindProperty(m_FontSize);
            root.Add(fontSizeField);
            fontSizeField.TrackPropertyValue(m_FontSize, ClampFontSize);

            root.Add(CreateEnumField<FontRenderingMode>(m_FontRenderingMode, Style.RenderingMode));
            root.Add(CreateEnumField<FontTextureCase>(m_TextureCase, Style.TextureCase));
            root.Add(CreateEnumField<AscentCalculationMode>(m_AscentCalculationMode, Style.AscentCalculationMode));
            root.Add(new PropertyField(m_UseLegacyBoundsCalculation, Style.BoundCalculation));
            root.Add(new PropertyField(m_ShouldRoundAdvanceValue, Style.ShouldRoundAdvanceValue));

            var customCharsField = CreateCustomCharsField();
            root.Add(customCharsField);

            var dynamicGroup = CreateDynamicGroup();
            root.Add(dynamicGroup);

            void UpdateGroupVisibility()
            {
                var mixed = m_TextureCase.hasMultipleDifferentValues;
                var textureCase = (FontTextureCase)m_TextureCase.intValue;
                customCharsField.style.display = !mixed && textureCase == FontTextureCase.CustomSet ? DisplayStyle.Flex : DisplayStyle.None;
                dynamicGroup.style.display = !mixed && textureCase == FontTextureCase.Dynamic ? DisplayStyle.Flex : DisplayStyle.None;
            }

            root.TrackPropertyValue(m_TextureCase, _ => UpdateGroupVisibility());
            UpdateGroupVisibility();

            root.Add(new IMGUIContainer(ApplyRevertGUI));
            return root;
        }

        static void ClampFontSize(SerializedProperty fontSize)
        {
            var clamped = Mathf.Clamp(fontSize.intValue, 1, 500);
            if (clamped == fontSize.intValue)
                return;
            fontSize.intValue = clamped;
            fontSize.serializedObject.ApplyModifiedProperties();
        }

        // These properties transfer as plain ints, so PropertyField would draw an int field instead of a popup.
        static EnumField CreateEnumField<TEnum>(SerializedProperty property, string label) where TEnum : Enum
        {
            var enumType = typeof(TEnum);
            var field = new EnumField(label, (Enum)Enum.ToObject(enumType, property.intValue));
            field.AddToClassList(EnumField.alignedFieldUssClassName);
            field.showMixedValue = property.hasMultipleDifferentValues;

            field.RegisterValueChangedCallback(evt =>
            {
                if (evt.newValue == null)
                    return;
                property.intValue = Convert.ToInt32(evt.newValue);
                property.serializedObject.ApplyModifiedProperties();
            });

            field.TrackPropertyValue(property, prop =>
            {
                field.showMixedValue = prop.hasMultipleDifferentValues;
                if (!prop.hasMultipleDifferentValues)
                    field.SetValueWithoutNotify((Enum)Enum.ToObject(enumType, prop.intValue));
            });

            return field;
        }

        TextField CreateCustomCharsField()
        {
            var customCharsField = new TextField(Style.CustomChars)
            {
                name = "custom-chars-field",
                multiline = true,
            };
            customCharsField.style.whiteSpace = WhiteSpace.Normal;
            customCharsField.AddToClassList(TextField.alignedFieldUssClassName);
            customCharsField.SetValueWithoutNotify(m_CustomCharacters.stringValue);
            customCharsField.showMixedValue = m_CustomCharacters.hasMultipleDifferentValues;

            customCharsField.RegisterValueChangedCallback(evt =>
            {
                var filtered = FilterCustomCharacters(evt.newValue);
                if (filtered != evt.newValue)
                {
                    var caretSource = evt.newValue.Substring(0, Mathf.Clamp(customCharsField.cursorIndex, 0, evt.newValue.Length));
                    var caret = FilterCustomCharacters(caretSource).Length;
                    customCharsField.SetValueWithoutNotify(filtered);
                    customCharsField.SelectRange(caret, caret);
                }

                m_CustomCharacters.stringValue = filtered;
                serializedObject.ApplyModifiedProperties();
            });

            customCharsField.TrackPropertyValue(m_CustomCharacters, prop =>
            {
                if (prop.stringValue != customCharsField.value)
                    customCharsField.SetValueWithoutNotify(prop.stringValue);
                customCharsField.showMixedValue = prop.hasMultipleDifferentValues;
            });

            return customCharsField;
        }

        static string FilterCustomCharacters(string value)
        {
            using var seenHandle = HashSetPool<char>.Get(out var seen);
            using var resultHandle = ListPool<char>.Get(out var result);
            var changed = false;
            foreach (var c in value)
            {
                if (c == '\n' || c == '\r')
                {
                    changed = true;
                    continue;
                }

                if (seen.Add(c))
                    result.Add(c);
                else
                    changed = true;
            }

            return changed ? new string(result.ToArray()) : value;
        }

        VisualElement CreateDynamicGroup()
        {
            var group = new VisualElement();
            group.Add(new PropertyField(m_IncludeFontData, Style.IncludeFontData));

            var familyNameField = new PropertyField(m_FontName, Style.FamilyName) { tooltip = Style.FamilyNameTooltip };
            familyNameField.SetEnabled(false);
            group.Add(familyNameField);

            var fontNamesField = new PropertyField(m_FontNames, Style.FontName);
            group.Add(fontNamesField);

            var referencesFoldout = new Foldout { text = Style.FontReferences, value = m_ReferencesExpanded };
            referencesFoldout.RegisterValueChangedCallback(evt => m_ReferencesExpanded = evt.newValue);
            referencesFoldout.Add(new HelpBox(Style.ReferencesInformation, HelpBoxMessageType.Info));

            var referencesList = new VisualElement();
            referencesFoldout.Add(referencesList);
            group.Add(referencesFoldout);

            void RefreshReferencesList()
            {
                referencesList.Clear();
                if (m_FallbackFontReferences.Count > 0)
                {
                    foreach (var font in m_FallbackFontReferences)
                    {
                        var objectField = new ObjectField
                        {
                            objectType = typeof(Font),
                            allowSceneObjects = false,
                            value = font,
                            showMixedValue = serializedObject.isEditingMultipleObjects && font == null,
                        };
                        objectField.SetEnabled(false);
                        referencesList.Add(objectField);
                    }
                }
                else
                {
                    referencesList.Add(new Label(Style.NoFontReference));
                }
            }

            RefreshReferencesList();
            fontNamesField.TrackPropertyValue(m_FontNames, _ =>
            {
                UpdateFontReferences();
                RefreshReferencesList();
            });

            return group;
        }
    }
}
